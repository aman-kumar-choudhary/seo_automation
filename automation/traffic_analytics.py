"""Campaign Referral Traffic and Search Visibility Analytics Monitor.

Estimates referral traffic impact, monthly impressions, and domain equity value
generated by published social bookmarks and backlinks for Innovions.
"""
from __future__ import annotations

import logging
from datetime import datetime, timezone
from dataclasses import dataclass
from database.models import CampaignAnalyticsResult
from content.utm import build_utm_url

logger = logging.getLogger(__name__)

# Base monthly audience multipliers for known domains
DOMAIN_TRAFFIC_TIERS: dict[str, tuple[str, int, float]] = {
    # domain: (tier, monthly_impressions_base, equity_dollar_value)
    "reddit.com": ("High Tier (Major Community)", 1500, 120.0),
    "linkedin.com": ("High Tier (Enterprise B2B)", 1200, 150.0),
    "medium.com": ("High Tier (Content Authority)", 800, 95.0),
    "dev.to": ("High Tier (Tech Community)", 950, 110.0),
    "news.ycombinator.com": ("High Tier (Tech Authority)", 1800, 180.0),
    "diigo.com": ("Medium Tier (Social Bookmarking)", 300, 45.0),
    "folkd.com": ("Medium Tier (Social Bookmarking)", 250, 40.0),
    "bizsugar.com": ("Medium Tier (Business News)", 320, 50.0),
    "slashdot.org": ("High Tier (Tech News)", 1100, 130.0),
    "scoop.it": ("Medium Tier (Content Curation)", 400, 55.0),
}


class TrafficAnalyticsTracker:
    """Estimates and tracks campaign referral traffic impact and backlink value."""

    def __init__(self, target_url: str = "https://innovions.org/"):
        self.target_url = target_url

    def estimate_platform_impact(
        self,
        domain: str,
        da: float = 30.0,
        is_dofollow: bool = False,
        quality_score: int = 70,
        cluster_name: str = "rfid",
    ) -> CampaignAnalyticsResult:
        """Estimates traffic impressions and monetary SEO equity value for a published backlink."""
        clean_d = domain.strip().lower().removeprefix("www.")
        now_ts = datetime.now(timezone.utc).isoformat()

        utm_url = build_utm_url(
            base_url=self.target_url,
            domain=clean_d,
            cluster_name=cluster_name,
        )

        if clean_d in DOMAIN_TRAFFIC_TIERS:
            tier, base_impressions, base_value = DOMAIN_TRAFFIC_TIERS[clean_d]
        else:
            if da >= 80:
                tier = "High Tier (Authority)"
                base_impressions = 800
                base_value = 100.0
            elif da >= 50:
                tier = "Medium Tier (Established)"
                base_impressions = 350
                base_value = 50.0
            else:
                tier = "Standard Tier (Niche Bookmark)"
                base_impressions = 150
                base_value = 25.0

        # Multipliers based on link equity and audit quality score
        quality_mult = max(0.2, quality_score / 100.0)
        dofollow_mult = 1.6 if is_dofollow else 1.0

        estimated_impressions = int(base_impressions * quality_mult * (1.2 if is_dofollow else 0.9))
        equity_val = round(base_value * quality_mult * dofollow_mult, 2)

        return CampaignAnalyticsResult(
            domain=clean_d,
            utm_url=utm_url,
            traffic_tier=tier,
            estimated_monthly_impressions=estimated_impressions,
            equity_value_score=equity_val,
            created_at=now_ts,
        )

    def summarize_campaign(self, analytics_rows: list[dict]) -> dict:
        """Aggregates all published platforms into total referral and equity summary."""
        total_impressions = sum(r.get("estimated_monthly_impressions", 0) for r in analytics_rows)
        total_equity = round(sum(r.get("equity_value_score", 0.0) for r in analytics_rows), 2)
        count = len(analytics_rows)

        return {
            "total_campaign_assets": count,
            "total_estimated_monthly_impressions": total_impressions,
            "total_estimated_monthly_referral_clicks": int(total_impressions * 0.035),  # 3.5% CTR estimate
            "total_domain_equity_value_usd": total_equity,
        }
